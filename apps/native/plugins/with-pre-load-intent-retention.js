/**
 * Keeps a deep link that reaches MainActivity before the app has loaded (#905, 2026-10-01).
 *
 * The state: the process is dead and its task is alive (opened once, sent to the background,
 * reclaimed by Android). A link then does not start a new activity — Android recreates
 * MainActivity from the task with its ORIGINAL intent and delivers the link to `onNewIntent`
 * in the same launch sequence, before any JS exists. Nothing downstream keeps it:
 *
 * - `ReactActivityDelegateWrapper.onNewIntent` (expo@57.0.26) returns `false` without calling a
 *   single lifecycle listener while its `loadAppReady` is incomplete, and on a release build
 *   expo-updates completes that off the main thread, after `onCreate` (`getDelayLoadAppHandler`
 *   in expo-updates@57.0.24 `UpdatesPackage.kt`). So expo-linking's
 *   `LinkingReactActivityLifecycleListener` never records the URL.
 * - `ReactActivity.onNewIntent` (react-native@0.86.3) then falls through to `Activity`, which
 *   does not call `setIntent`, so `IntentModule.getInitialURL` keeps reading the launcher intent.
 *
 * expo-router's Android initial URL is exactly that read (`getInitialURLWithTimeout` in
 * expo-router@57.0.24 `build/fork/useLinking.native.js`), so the app opened on its default
 * screen and a recovery or confirmation link was spent for nothing. All four read 2026-10-01.
 *
 * The override makes the pending intent the activity's intent, which is the one thing the JS
 * side reads at boot. It does so only while no React context exists: once there is one, React
 * Native emits the `url` event itself, and retaining then would make a JS reload in the same
 * process replay a link that was already handled. The retained intent is whatever arrived —
 * a launcher intent too — so a launcher start over a task whose record still names an old link
 * replaces it rather than replaying it.
 *
 * `android/` is generated, so MainActivity can only be changed from a config plugin.
 * `native-config.test.ts` pins the wiring and the pure half below.
 */
const { withMainActivity } = require('expo/config-plugins');

const MARKER = '@athanor/pre-load-intent-retention';
const INTENT_IMPORT = 'import android.content.Intent';

const OVERRIDE = `
  // ${MARKER} — generated by plugins/with-pre-load-intent-retention.js
  override fun onNewIntent(intent: Intent) {
    if (reactHost?.currentReactContext == null) {
      setIntent(intent)
    }
    super.onNewIntent(intent)
  }
`;

/**
 * The pure half: add the `onNewIntent` override to MainActivity.kt's source, idempotently.
 * @param {string} contents
 */
function addPreLoadIntentRetention(contents) {
  if (contents.includes(MARKER)) return contents;
  if (/override\s+fun\s+onNewIntent\b/.test(contents)) {
    throw new Error(
      'with-pre-load-intent-retention: MainActivity already overrides onNewIntent; merge the two by hand.',
    );
  }
  const classEnd = contents.lastIndexOf('}');
  if (!/class\s+MainActivity\b/.test(contents) || classEnd === -1 || !/^import /m.test(contents)) {
    throw new Error('with-pre-load-intent-retention: could not find the MainActivity class.');
  }
  const withOverride = `${contents.slice(0, classEnd)}${OVERRIDE}${contents.slice(classEnd)}`;
  return new RegExp(`^${INTENT_IMPORT}$`, 'm').test(withOverride)
    ? withOverride
    : withOverride.replace(/^import /m, `${INTENT_IMPORT}\nimport `);
}

/** @type {import('expo/config-plugins').ConfigPlugin} */
const withPreLoadIntentRetention = (config) =>
  withMainActivity(config, (mod) => {
    if (mod.modResults.language !== 'kt') {
      throw new Error('with-pre-load-intent-retention: MainActivity is not Kotlin.');
    }
    mod.modResults.contents = addPreLoadIntentRetention(mod.modResults.contents);
    return mod;
  });

module.exports = withPreLoadIntentRetention;
module.exports.addPreLoadIntentRetention = addPreLoadIntentRetention;
module.exports.MARKER = MARKER;
